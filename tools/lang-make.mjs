// Writes assets/lang/<code>.js from the translation sources:
//   tools/lang-src/keys.json      the English text, in a fixed order
//   tools/lang-src/<code>.txt     one line per text: "<index>|<translation>" ("=" keeps the English)
//   tools/lang-src/patterns.mjs   text with numbers in it ("3 files are ready"), per language
// Usage: node tools/lang-make.mjs fr es pt id tr hi   (no argument = every .txt found)
// To add text later: append it to keys.json, add its line to each .txt, run this, then node tools/build.mjs.
import fs from 'node:fs';
import path from 'node:path';
import PATTERNS from './lang-src/patterns.mjs';

const SRC = path.join(process.cwd(), 'tools/lang-src');
const keys = JSON.parse(fs.readFileSync(path.join(SRC, 'keys.json'), 'utf8'));
let langs = process.argv.slice(2);
if (!langs.length) langs = fs.readdirSync(SRC).filter((f) => /^[a-z]{2}\.txt$/.test(f)).map((f) => f.slice(0, 2));

for (const lang of langs) {
  const lines = fs.readFileSync(path.join(SRC, lang + '.txt'), 'utf8').split(/\r?\n/).filter((l) => l.trim());
  const dict = {};
  const seen = new Set();
  for (const line of lines) {
    const m = line.match(/^(\d+)\|(.*)$/);
    if (!m) throw new Error(`${lang}.txt: bad line: ${line}`);
    const i = Number(m[1]);
    if (i >= keys.length) throw new Error(`${lang}.txt: index ${i} has no English text`);
    if (seen.has(i)) throw new Error(`${lang}.txt: index ${i} twice`);
    seen.add(i);
    const v = m[2].trim();
    dict[keys[i]] = v === '=' ? keys[i] : v;
  }
  const missing = keys.map((k, i) => i).filter((i) => !seen.has(i));
  const pats = (PATTERNS[lang] || []).map(([re, rep]) => `    [/${re}/, ${JSON.stringify(rep)}],`).join('\n');
  const out = `/* ${lang}: dictionary for the /${lang}/ pages. Generated by tools/lang-make.mjs from tools/lang-src - do not edit. */
(window.FM_LANG_DICTS = window.FM_LANG_DICTS || {}).${lang} = {
  dict: ${JSON.stringify(dict, null, 1).replace(/\n/g, '\n  ')},
  patterns: [
${pats}
  ],
};
`;
  fs.writeFileSync(path.join(process.cwd(), 'assets/lang', lang + '.js'), out);
  console.log(`${lang}: ${Object.keys(dict).length} texts, ${(PATTERNS[lang] || []).length} patterns${missing.length ? `, MISSING ${missing.length}: ${missing.slice(0, 20).join(', ')}` : ''}`);
}
